from pathlib import Path
from app.schemas.transaction import TransactionPayload, FinalDecision
from app.core.logger import logger

REPORTS_DIR = Path("reports")
REPORTS_DIR.mkdir(exist_ok=True)

def generate_audit_report(transaction: TransactionPayload, decision: FinalDecision) -> Path:
    """Generates a formal Markdown audit report for banking compliance in English."""
    logger.info(f"Generating audit report for TX: {decision.transaction_id}")
    
    file_path = REPORTS_DIR / f"audit_{decision.transaction_id}.md"
    
    report_content = f"""# 🛡️ AUDIT & COMPLIANCE REPORT - FINGUARD

**Transaction ID:** `{decision.transaction_id}`  
**Timestamp (UTC):** `{decision.timestamp}`  
**Pipeline Status:** `COMPLETED`

---

## 1. Transaction Details
- **Source Account:** `{transaction.account_id}`
- **Requested Amount:** `${transaction.amount:,.2f}`
- **Operation Location:** `{transaction.location}`

## 2. Customer Behavioral Profile
- **Average Monthly Transfer:** `${transaction.customer_profile.avg_monthly_transfer:,.2f}`
- **Usual Location:** `{transaction.customer_profile.usual_location}`

---

## 3. Risk Assessment (LLM Agent - Qwen 2.5)
- **Identified Risk Level:** **{decision.risk_level}**
- **AI Technical Assessment:**  
  > "{decision.llm_explanation}"

---

## 4. Recommended Compliance Action
- **Final Decision:** `{decision.action}`

---
*Report automatically generated by FinGuard AI Engine.*
"""

    with open(file_path, "w", encoding="utf-8") as f:
        f.write(report_content)
        
    logger.info(f"Audit report successfully saved to: {file_path}")
    return file_path